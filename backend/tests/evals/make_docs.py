# --- a deterministic minimal PDF ------------------------------------------------------


def _pdf_string(text: str) -> bytes:
    raw = text.encode("cp1252")
    return b"(" + raw.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)") + b")"


def _page_stream(lines: list[str]) -> bytes:
    parts = [b"BT", b"/F1 11 Tf", b"14 TL", b"50 790 Td"]
    for line in lines:
        parts.append(_pdf_string(line) + b" Tj T*")
    parts.append(b"ET")
    return b"\n".join(parts)


def build_pdf(pages: list[list[str]]) -> bytes:
    """A PDF with one A4 page per list of lines; the same input gives the same bytes."""
    objects: list[bytes] = []  # object n is objects[n - 1]
    page_ids = [3 + 2 * i for i in range(len(pages))]
    font_id = 3 + 2 * len(pages)
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    kids = b" ".join(b"%d 0 R" % pid for pid in page_ids)
    objects.append(b"<< /Type /Pages /Kids [%s] /Count %d >>" % (kids, len(pages)))
    for pid, lines in zip(page_ids, pages, strict=True):
        objects.append(
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
            b"/Resources << /Font << /F1 %d 0 R >> >> /Contents %d 0 R >>" % (font_id, pid + 1)
        )
        stream = _page_stream(lines)
        objects.append(b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream))
    objects.append(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
    )

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n%s\nendobj\n" % (number, body)
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        xref,
    )
    return bytes(out)


def doc_pdf(doc: Doc) -> bytes:
    return build_pdf(doc.pages)


def main(argv: list[str]) -> None:
    out_dir = Path(argv[1]) if len(argv) > 1 else Path(__file__).parent / "docs"
    out_dir.mkdir(parents=True, exist_ok=True)
    for doc in DOCS:
        (out_dir / f"{doc.name}.pdf").write_bytes(doc_pdf(doc))
        print(out_dir / f"{doc.name}.pdf")


if __name__ == "__main__":
    main(sys.argv)
